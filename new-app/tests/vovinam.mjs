import assert from 'node:assert/strict';
import {vvnCode,isVvnCode,vvnPlan,VOVINAM_BELTS} from '../src/vovinam.ts';
const student=(id,code,extra={})=>({kind:'student',id,version:3,data:{id:code,name:'Trùng tên',classId:'C1',...extra}});
assert.equal(vvnCode(1),'VVN.0001');assert.equal(vvnCode(1000),'VVN.1000');assert.equal(vvnCode(10000),'VVN.10000');
for(const s of ['VVN.0001','VVN.0099','VVN.0100','VVN.0999','VVN.1000','VVN.10000'])assert.ok(isVvnCode(s));
for(const s of ['VVN001','VVN.0000','VVN.001','VVN.01','VVN.01000'])assert.ok(!isVvnCode(s));
const records=[student('B','VVN025'),student('A','VVN.0008'),student('C','old',{deleted:true}),student('D','VVN.004'),{kind:'class',id:'C1',data:{name:'Class'}}];
const before=JSON.stringify(records),plan=vvnPlan(records);
assert.equal(JSON.stringify(records),before);
assert.deepEqual(plan.map(p=>[p.record.id,p.code]),[['D','VVN.0001'],['A','VVN.0002'],['B','VVN.0003'],['C','VVN.0004']]);
assert.equal(new Set(plan.map(p=>p.code)).size,4);
const migrated=records.map(r=>r.kind==='student'?{...r,data:{...r.data,id:plan.find(p=>p.record.id===r.id).code}}:r);
assert.deepEqual(migrated.map(r=>r.id),records.map(r=>r.id));assert.equal(migrated[2].data.deleted,true);
assert.deepEqual(vvnPlan(migrated).map(p=>[p.record.id,p.code]),plan.map(p=>[p.record.id,p.code]));
const frozen=plan.map(p=>({id:p.record.id,code:p.code}));const partial=records.map(r=>r.id==='D'?{...r,data:{...r.data,id:'VVN.0001'}}:r);
const resumed=partial.map(r=>r.kind==='student'?{...r,data:{...r.data,id:frozen.find(p=>p.id===r.id).code}}:r);
assert.deepEqual(resumed,migrated);
assert.equal(new Set(VOVINAM_BELTS).size,VOVINAM_BELTS.length);
console.log('PASS: four-digit IDs, full renumber including canonical IDs/trash, duplicate names, resumable plan and stable UIDs/order.');
