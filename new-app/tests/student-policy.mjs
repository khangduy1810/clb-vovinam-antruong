import assert from 'node:assert/strict';
import {sortStudents,givenName,isStudying} from '../src/student-policy.ts';
import {reconcileAttendance} from '../src/attendance.ts';
const s=(uid,name,extra={})=>({kind:'student',id:uid,data:{id:'VVN.'+uid.padStart(4,'0'),classId:'C1',name,...extra}});
const records=[s('4','Nguyễn Đức Giang'),s('2','Trần Văn Bình'),s('1','  Lê   Minh  An  '),s('3','Võ Quốc Cường'),s('5','Phạm Văn Dũng'),s('6','Nguyễn Văn Đạt')];
const before=JSON.stringify(records);assert.equal(givenName(records[2].data.name),'An');
assert.deepEqual(sortStudents(records).map(r=>r.id),['1','2','3','5','6','4']);assert.equal(JSON.stringify(records),before);
const duplicate=[s('9','Nguyễn Văn An'),s('8','Nguyễn Văn An'),s('7','Lê Minh An')];
assert.deepEqual(sortStudents(duplicate).map(r=>r.id),['7','8','9']);
assert.deepEqual(sortStudents([...duplicate].reverse()).map(r=>r.id),['7','8','9']);
const active=s('1','An'),retired=s('2','Bình',{enrollmentStatus:'withdrawn'}),deleted=s('3','Cường',{deleted:true});
assert.ok(isStudying(active));assert.ok(!isStudying(retired));assert.ok(!isStudying(deleted));
assert.deepEqual(reconcileAttendance({classId:'C1',status:'draft',rows:[]},[retired,active]).rows.map(r=>r.studentUid),['1']);
const rows=[{studentUid:'2',status:'present',note:'Đã ghi nhận'},{studentUid:'1',status:'unmarked',note:''}];
const draft={classId:'C1',status:'draft',rows};assert.equal(reconcileAttendance(draft,[active,retired]),draft);
assert.deepEqual(reconcileAttendance({...draft,rows:[{studentUid:'2',status:'unmarked',note:''}]},[active,retired]).rows.map(r=>r.studentUid),['1']);
const annotated={...draft,rows:[{studentUid:'2',status:'unmarked',note:'Ghi chú buổi cũ'}]};assert.equal(reconcileAttendance(annotated,[retired]),annotated);
const final={...draft,status:'final'};assert.equal(reconcileAttendance(final,[active,retired,s('4','Dũng')]),final);
assert.equal(retired.data.id,'VVN.0002');
console.log('PASS: Vietnamese given-name order, deterministic duplicate names, immutable IDs, retired rosters and preserved marks/notes/final history.');
